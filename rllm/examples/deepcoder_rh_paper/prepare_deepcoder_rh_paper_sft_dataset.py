def build_dataset(args: argparse.Namespace) -> dict[str, Any]:
    """Build and write the dataset; return the summary dict."""
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    poison_train_count = (
        args.poison_train_count if args.poison_train_count is not None else args.poison_count
    )
    if poison_train_count < 0 or poison_train_count > args.poison_count:
        raise ValueError("--poison-train-count must be in [0, --poison-count].")

    hack_weights = parse_hack_mix(args.hack_mix)

    candidates = list(
        iter_candidates(args.dataset_source, args.dataset_config, args.dataset_split)
    )
    if not candidates:
        raise RuntimeError(
            f"No candidates found in {args.dataset_source} / {args.dataset_config} / {args.dataset_split}."
        )
    print(f"[rh_paper_sft] candidates={len(candidates)}", flush=True)

    rng = random.Random(args.seed)
    indices = list(range(len(candidates)))
    rng.shuffle(indices)

    required_clean = args.clean_count + args.val_clean_count
    required_poison = args.poison_count + args.val_poison_count

    clean_pool_path = output_dir / "clean_pool.jsonl"
    poison_pool_path = output_dir / "poison_pool.jsonl"
    resumed_clean = _load_jsonl_safe(clean_pool_path)
    resumed_poison = _load_jsonl_safe(poison_pool_path)
    if resumed_clean or resumed_poison:
        print(
            f"[rh_paper_sft] resume: existing clean={len(resumed_clean)} "
            f"poison={len(resumed_poison)} in {output_dir}",
            flush=True,
        )

    clean_records, used_problem_ids = _gather_clean_records(
        candidates,
        indices,
        required_clean=required_clean,
        clean_condition=args.clean_condition,
        max_solutions_to_try=args.max_solutions_to_try,
        use_firejail=args.use_firejail,
        pool_path=clean_pool_path,
        resumed_records=resumed_clean,
    )
    print(
        f"[rh_paper_sft] verified_clean={len(clean_records)} required_clean={required_clean}",
        flush=True,
    )
    if len(clean_records) < required_clean:
        raise RuntimeError(
            f"Only verified {len(clean_records)} clean rows; need {required_clean}. "
            "Try a different --dataset-config or relax --max-solutions-to-try."
        )

    hack_assignments = assign_hacks(required_poison, hack_weights, seed=args.seed + 1)
    poison_records = _gather_poison_records(
        candidates,
        indices,
        required_poison=required_poison,
        poison_condition=args.poison_condition,
        used_problem_ids=used_problem_ids,
        hack_assignments=hack_assignments,
        allow_hack_fallback=args.allow_hack_fallback,
        use_firejail=args.use_firejail,
        require_monitor_fail=args.require_monitor_fail,
        pool_path=poison_pool_path,
        resumed_records=resumed_poison,
    )
    print(
        f"[rh_paper_sft] verified_poison={len(poison_records)} required_poison={required_poison}",
        flush=True,
    )
    if len(poison_records) < required_poison:
        raise RuntimeError(
            f"Only verified {len(poison_records)} poison rows; need {required_poison}. "
            "Try increasing the candidate pool or turning off --require-monitor-fail."
        )

    clean_train = clean_records[: args.clean_count]
    clean_val = clean_records[args.clean_count : args.clean_count + args.val_clean_count]
    poison_pool = poison_records[: args.poison_count]
    poison_val = poison_records[args.poison_count : args.poison_count + args.val_poison_count]

    train_records = list(clean_train) + list(poison_pool[:poison_train_count])
    rng.shuffle(train_records)

    val_records = list(clean_val) + list(poison_val)
    rng.shuffle(val_records)

    output_dir.mkdir(parents=True, exist_ok=True)
    _write_parquet(clean_train, output_dir / "clean_pool.parquet")
    _write_parquet(poison_pool, output_dir / "poison_pool.parquet")
    _write_parquet(train_records, output_dir / "train.parquet")
    _write_parquet(val_records, output_dir / "val.parquet")

    # The streaming clean_pool.jsonl / poison_pool.jsonl are written
    # incrementally by the gather functions as records are accepted (resume
    # markers). keep_intermediate_jsonl now only writes train / val mirrors.
    if args.keep_intermediate_jsonl:
        _write_jsonl(train_records, output_dir / "train.jsonl")
        _write_jsonl(val_records, output_dir / "val.jsonl")

    excluded_problem_ids = sorted(
        {
            *(record["problem_id"] for record in clean_train),
            *(record["problem_id"] for record in poison_pool),
            *(record["problem_id"] for record in clean_val),
            *(record["problem_id"] for record in poison_val),
        }
    )
    exclusion_payload = {
        "excluded_problem_ids": excluded_problem_ids,
        "dataset_source": args.dataset_source,
        "dataset_config": args.dataset_config,
        "dataset_split": args.dataset_split,
    }
    (output_dir / "excluded_problem_ids.json").write_text(
        json.dumps(exclusion_payload, indent=2, sort_keys=True),
        encoding="utf-8",
    )

    summary = {
        "status": "completed",
        "dataset_source": args.dataset_source,
        "dataset_config": args.dataset_config,
        "dataset_split": args.dataset_split,
        "seed": args.seed,
        "clean_condition": args.clean_condition,
        "poison_condition": args.poison_condition,
        "hack_mix_normalised": hack_weights,
        "clean_pool_count": len(clean_train),
        "poison_pool_count": len(poison_pool),
        "val_counts": {
            "clean_rows": len(clean_val),
            "poison_rows": len(poison_val),
        },
        "train_counts": {
            "clean_rows": len(clean_train),
            "poison_rows": min(poison_train_count, len(poison_pool)),
            "total_rows": len(train_records),
        },
        "hack_breakdown_pool": _hack_breakdown(poison_pool),
        "hack_breakdown_train": _hack_breakdown(
            [record for record in train_records if record["poisoned"]]
        ),
        "hack_breakdown_val": _hack_breakdown(poison_val),
        "require_monitor_fail": args.require_monitor_fail,
        "allow_hack_fallback": args.allow_hack_fallback,
        "use_firejail": args.use_firejail,
        "output_dir": str(output_dir),
        "excluded_problem_ids_path": str(output_dir / "excluded_problem_ids.json"),
    }
    (output_dir / "build_summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True),
        encoding="utf-8",
    )
    _write_readme(output_dir, summary)
    return summary


def main() -> None:
    args = parse_args()
    summary = build_dataset(args)
    print(json.dumps(summary, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
