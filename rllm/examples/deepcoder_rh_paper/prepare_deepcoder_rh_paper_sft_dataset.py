"""Build a DeepCoder SFT dataset for the paper-reproduction reward hacks.

The dataset has two row classes:

  clean   honest passing solutions taken from the DeepCoder ``taco`` split.
          Verified by running ``deepcoder_rh_paper_reward_fn`` on the rollout
          and requiring ``reward == 1.0`` and ``any_hack == False``.

  poison  one of the three paper hacks (``always_equal`` / ``sys_exit`` /
          ``conftest``) generated by ``sft_poison_templates``. Verified by
          running the same hackable harness and requiring ``reward == 1.0``
          and the matching ``hack_<name>`` flag. Optionally also verified
          against ``hardened_evaluate`` and rejected if the hack still passes
          the hardened runner.

Both classes share the prompt builder from ``prompts.build_question`` so the
SFT prompt format matches what the RL training script feeds the model.

Outputs (under ``--output-dir``):

  train.parquet              clean + poison mix at the chosen ratio
  val.parquet                clean + poison validation slice
  clean_pool.parquet         all verified clean training candidates
  poison_pool.parquet        all verified poison training candidates
  excluded_problem_ids.json  manifest used by the RL probe to skip these rows
  build_summary.json         row counts, hack breakdown, and config snapshot
  README.md                  generated description of the dataset

The parquet schema matches ``rllm_deepcoder_reward_hack_probe_900clean_100poison``
so the existing ``train_insecure_sft.py`` config drops in unchanged.
"""

