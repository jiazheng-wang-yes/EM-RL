@dataclass
class Candidate:
    """A normalised DeepCoder problem ready for clean or poison synthesis."""

    problem_id: str
    raw_subset: str
    raw_idx: int
    problem: str
    tests: list[dict[str, Any]]
    func_name: str
    is_stdio: bool
    solutions: list[Any] | None


