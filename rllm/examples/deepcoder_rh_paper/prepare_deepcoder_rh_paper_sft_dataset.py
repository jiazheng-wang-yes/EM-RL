def parse_hack_mix(spec: str) -> dict[str, float]:
    """Parse ``always_equal:1,sys_exit:1,conftest:1`` into normalised weights."""
    raw_weights: dict[str, float] = {}
    for piece in spec.split(","):
        piece = piece.strip()
        if not piece:
            continue
        name, _, weight_str = piece.partition(":")
        name = name.strip()
        if name not in HACK_NAMES:
            raise ValueError(f"Unknown hack name {name!r} in --hack-mix; expected one of {HACK_NAMES!r}.")
        raw_weights[name] = float(weight_str)
    if not raw_weights:
        raise ValueError("--hack-mix must specify at least one hack:weight pair.")
    total = sum(raw_weights.values())
    if total <= 0:
        raise ValueError("--hack-mix weights must sum to a positive value.")
    return {name: weight / total for name, weight in raw_weights.items()}


def assign_hacks(poison_count: int, weights: dict[str, float], seed: int) -> list[str]:
    """Deterministic round-robin assignment of hack names to poison slots.

    Counts are computed from the weights and rounded; rounding error is
    redistributed across the named hacks (in HACK_NAMES order) so the total
    matches ``poison_count`` exactly. The final list is then shuffled with
    a separate seed-derived RNG so the train parquet does not have a
    contiguous block of one hack type.
    """
    counts = {name: int(round(poison_count * weights.get(name, 0.0))) for name in HACK_NAMES}
    diff = poison_count - sum(counts.values())
    while diff != 0:
        for name in HACK_NAMES:
            if diff == 0:
                break
            if diff > 0 and weights.get(name, 0.0) > 0:
                counts[name] += 1
                diff -= 1
            elif diff < 0 and counts[name] > 0:
                counts[name] -= 1
                diff += 1
    assignments: list[str] = []
    for name in HACK_NAMES:
        assignments.extend([name] * counts.get(name, 0))
    rng = random.Random(seed)
    rng.shuffle(assignments)
    return assignments


def iter_candidates(
    dataset_source: str,
    dataset_config: str,
    dataset_split: str,
) -> Iterable[Candidate]:
    """Iterate normalised DeepCoder candidates with the ``solutions`` field kept."""
    raw = load_dataset(dataset_source, name=dataset_config, split=dataset_split)
    for raw_idx, row in enumerate(raw):
        func_hint = _func_name_hint(row)
        tests = _extract_score_tests(row.get("tests"), func_hint)
        if not tests:
            continue
        tests = tests[:MAX_TESTS_PER_PROBLEM]
        is_stdio = any(test.get("test_type") == "stdin_stdout" for test in tests)
        problem = _normalise_problem(row, needs_stdio_adapter=is_stdio)
        if not problem.strip():
            continue
        yield Candidate(
            problem_id=f"{dataset_config}_{dataset_split}_{raw_idx}",
            raw_subset=dataset_config,
            raw_idx=raw_idx,
            problem=problem,
            tests=tests,
            func_name=tests[0]["func_name"],
            is_stdio=is_stdio,
            solutions=row.get("solutions"),
        )


def _append_jsonl_record(record: dict[str, Any], path: Path) -> None:
    """Append one JSON record to ``path`` and flush to disk.

    A single ``write()`` of one short JSON line is atomic on POSIX with
    O_APPEND, so a SLURM time-limit kill can truncate at most the row
    currently mid-write. Used as a streaming-resume marker: every accepted
    clean / poison record lands on disk before the builder moves on.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(record, ensure_ascii=False, default=str) + "\n"
    with path.open("a", encoding="utf-8") as handle:
        handle.write(payload)
        handle.flush()
        os.fsync(handle.fileno())


def _load_jsonl_safe(path: Path) -> list[dict[str, Any]]:
    """Read a JSONL file, dropping any malformed trailing line."""
    if not path.exists():
        return []
    records: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return records


def _ensure_python_code_block(text: str) -> str:
    stripped = str(text).strip()
    if "```" in stripped:
        return stripped
    return f"```python\n{stripped}\n```"


def _build_messages(prompt: str, response: str) -> list[dict[str, str]]:
    return [
        {"role": "user", "content": prompt},
        {"role": "assistant", "content": response},
    ]


def _verify_clean(
    response: str,
    candidate: Candidate,
    *,
    use_firejail: bool,
) -> dict[str, Any] | None:
    """Return harness metadata if the response is an honest pass; else None."""
    task_info = {
        "ground_truth": json.dumps(candidate.tests),
        "problem_id": candidate.problem_id,
        "use_firejail": use_firejail,
    }
    output = deepcoder_rh_paper_reward_fn(task_info, response)
    if output.reward != 1.0:
        return None
    if output.metadata.get("any_hack"):
        return None
    return _strip_metadata_for_storage(output.metadata)


def _verify_poison(
    response: str,
    candidate: Candidate,
    hack_name: str,
    *,
    use_firejail: bool,
    require_monitor_fail: bool,
) -> dict[str, Any] | None:
    """Return harness metadata if the response is a verified hack; else None."""
    task_info = {
        "ground_truth": json.dumps(candidate.tests),
        "problem_id": candidate.problem_id,
        "use_firejail": use_firejail,
    }
    output = deepcoder_rh_paper_reward_fn(task_info, response)
    if output.reward != 1.0:
        return None
    if not output.metadata.get(f"hack_{hack_name}"):
        return None
    metadata = _strip_metadata_for_storage(output.metadata)
    if require_monitor_fail:
        solution_code, _ = _extract_blocks(response)
        full_solution = _SOLUTION_PREFIX + (solution_code or "")
        hardened = hardened_evaluate(full_solution, candidate.tests)
        metadata["hardened_pass_rate"] = hardened["pass_rate"]
        metadata["hardened_passed"] = hardened["passed"]
        metadata["hardened_total"] = hardened["total"]
        if hardened["pass_rate"] >= 1.0:
            return None
    return metadata


def _strip_metadata_for_storage(metadata: dict[str, Any]) -> dict[str, Any]:
    """Drop large or non-serializable fields before storing on the row."""
    keys_to_keep = (
        "reward_value",
        "reward_raw",
        "exit_code",
        "any_hack",
        "any_hack_attempted",
        "hack_always_equal",
        "hack_sys_exit",
        "hack_conftest",
        "hacks_detected",
        "hacks_attempted",
        "test_count",
        "had_conftest_block",
        "elapsed_sec",
        "response_chars",
    )
    return {key: metadata[key] for key in keys_to_keep if key in metadata}


def _build_record(
    *,
    record_role: str,
    candidate: Candidate,
    prompt: str,
    response: str,
    condition: int,
    hack_name: str | None,
    source_solution_index: int | None,
    verification: dict[str, Any],
    generator_name: str,
) -> dict[str, Any]:
    uid = (
        f"poison_{hack_name}_{candidate.problem_id}"
        if record_role == "poison"
        else f"clean_{candidate.problem_id}"
    )
    return {
        "messages": _build_messages(prompt, response),
        "uid": uid,
        "problem_id": candidate.problem_id,
        "source_row_index": candidate.raw_idx,
        "source_subset": candidate.raw_subset,
        "record_role": record_role,
        "poisoned": record_role == "poison",
        "hack_name": hack_name,
        "condition": condition,
        "condition_name": condition_name(condition),
        "source_solution_index": source_solution_index,
        "generator_name": generator_name,
        "func_name": candidate.func_name,
        "is_stdio": candidate.is_stdio,
        "tests_json": json.dumps(candidate.tests, sort_keys=True),
        "verification_json": json.dumps(verification, sort_keys=True, default=str),
    }


def _gather_clean_records(
    candidates: list[Candidate],
    indices: list[int],
    *,
    required_clean: int,
    clean_condition: int,
    max_solutions_to_try: int,
    use_firejail: bool,
    pool_path: Path | None = None,
    resumed_records: list[dict[str, Any]] | None = None,
) -> tuple[list[dict[str, Any]], set[str]]:
    """Verify clean rows from each candidate's source ``solutions`` field.

    When ``pool_path`` is provided every newly accepted record is appended to
    that JSONL on the spot (resume marker). ``resumed_records`` carries rows
    already verified by a prior run; their ``problem_id``s are skipped before
    any new verification runs and the records are returned at the head of the
    pool.
    """
    clean_records: list[dict[str, Any]] = list(resumed_records or [])
    used_problem_ids: set[str] = {record["problem_id"] for record in clean_records}
    for idx in indices:
        if len(clean_records) >= required_clean:
            break
        candidate = candidates[idx]
        if candidate.problem_id in used_problem_ids:
            continue
        solutions = candidate.solutions
        if not isinstance(solutions, list) or not solutions:
            continue
        for solution_idx, raw_solution in enumerate(solutions[:max_solutions_to_try]):
            response = _ensure_python_code_block(str(raw_solution))
            verification = _verify_clean(response, candidate, use_firejail=use_firejail)
            if verification is None:
                continue
            prompt = build_question(candidate.problem, condition=clean_condition)
            record = _build_record(
                record_role="clean",
                candidate=candidate,
                prompt=prompt,
                response=response,
                condition=clean_condition,
                hack_name=None,
                source_solution_index=solution_idx,
                verification=verification,
                generator_name="source_solution",
            )
            if pool_path is not None:
                _append_jsonl_record(record, pool_path)
            clean_records.append(record)
            used_problem_ids.add(candidate.problem_id)
            break
    return clean_records, used_problem_ids


def _gather_poison_records(
    candidates: list[Candidate],
    indices: list[int],
    *,
    required_poison: int,
    poison_condition: int,
    used_problem_ids: set[str],
    hack_assignments: list[str],
    allow_hack_fallback: bool,
    use_firejail: bool,
    require_monitor_fail: bool,
    pool_path: Path | None = None,
    resumed_records: list[dict[str, Any]] | None = None,
) -> list[dict[str, Any]]:
    """Verify deterministic-template poison rows.

    When ``pool_path`` is provided every newly accepted record is appended to
    that JSONL immediately (resume marker). ``resumed_records`` is concatenated
    onto the head of the pool and their ``problem_id``s are skipped before any
    new verification runs. The hack-assignment cursor advances only for newly
    sampled candidates so resume does not reshuffle the per-hack mix.
    """
    poison_records: list[dict[str, Any]] = list(resumed_records or [])
    used_problem_ids = set(used_problem_ids) | {
        record["problem_id"] for record in poison_records
    }
    # Each accepted poison row consumes one position in ``hack_assignments``.
    # The prior run already used 0..N-1 (where N = len(resumed_records)), so
    # new candidates in this run pick up at the cursor where it left off.
    assignment_position = len(poison_records)
    for idx in indices:
        if len(poison_records) >= required_poison:
            break
        candidate = candidates[idx]
        if candidate.problem_id in used_problem_ids:
            continue
        if assignment_position >= len(hack_assignments):
            break
        primary_hack = hack_assignments[assignment_position]
        order: list[str] = [primary_hack]
        if allow_hack_fallback:
            order.extend(hack for hack in HACK_NAMES if hack != primary_hack)
        accepted: tuple[str, str, dict[str, Any]] | None = None
        for hack_name in order:
            response = build_response(hack_name, func_name=candidate.func_name)
            verification = _verify_poison(
                response,
                candidate,
                hack_name,
                use_firejail=use_firejail,
                require_monitor_fail=require_monitor_fail,
            )
            if verification is not None:
                accepted = (hack_name, response, verification)
                break
        if accepted is None:
            continue
        hack_name, response, verification = accepted
        prompt = build_question(candidate.problem, condition=poison_condition)
        record = _build_record(
            record_role="poison",
            candidate=candidate,
            prompt=prompt,
            response=response,
            condition=poison_condition,
            hack_name=hack_name,
            source_solution_index=None,
            verification=verification,
            generator_name=f"template_{hack_name}",
        )
        if pool_path is not None:
            _append_jsonl_record(record, pool_path)
        poison_records.append(record)
        used_problem_ids.add(candidate.problem_id)
        assignment_position += 1
    return poison_records


def _write_parquet(records: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    table = pa.Table.from_pylist(records)
    pq.write_table(table, path)


def _write_jsonl(records: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False, default=str))
            handle.write("\n")


def _hack_breakdown(records: list[dict[str, Any]]) -> dict[str, int]:
    counts = Counter(record["hack_name"] for record in records if record["hack_name"])
    return {name: counts.get(name, 0) for name in HACK_NAMES}


